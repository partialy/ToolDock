const Database=require('better-sqlite3')
const path=require('node:path')
const fs=require('node:fs')
const p=path.join(process.env.APPDATA,'ToolDock-Dev','data','tooldock.sqlite')
if(!fs.existsSync(p))throw Error('开发数据库尚未生成: '+p)
const db=new Database(p,{readonly:true,fileMustExist:true})
console.log('db',p)
console.log('categories',JSON.stringify(db.prepare('select id,name,is_system from categories').all()))
console.log('tools',JSON.stringify(db.prepare('select id,name,type,is_builtin from tools').all()))
console.log('integrity',db.pragma('integrity_check',{simple:true}))
db.close()
